# ── Helper functions ──────────────────────────────────────────────────

def _safe_json_parse(val):
    """Parse JSON safely."""
    if pd.isna(val) or val == 'null':
        return None
    if isinstance(val, str):
        try:
            return json.loads(val)
        except:
            return None
    return val

def parse_json_columns(df, json_columns):
    """Convert JSON column to parsed dict."""
    for col in json_columns:
        if col in df.columns:
            df[col] = df[col].apply(_safe_json_parse)
    return df

def build_merge_key(df):
    """Ensure date/datetime columns are properly typed.
    Raw parquet uses 'timestamp' column, not 'datetime'."""
    df = df.copy()
    if 'date' in df.columns:
        df['date'] = pd.to_datetime(df['date']).dt.date
    if 'timestamp' in df.columns:
        df['timestamp'] = pd.to_datetime(df['timestamp'])
        if 'date' not in df.columns:
            df['date'] = df['timestamp'].dt.date
        if 'datetime' not in df.columns:
            df['datetime'] = df['timestamp']  # alias for compat with 02_feature_engineering
    elif 'datetime' in df.columns:
        df['datetime'] = pd.to_datetime(df['datetime'])
        if 'date' not in df.columns:
            df['date'] = df['datetime'].dt.date
    return df

def aggregate_numeric(df, data_col, agg_cols=['subject_id','date'], agg_funcs=None):
    """Aggregate numeric column."""
    if agg_funcs is None:
        agg_funcs = ['mean', 'std', 'min', 'max', 'count']
    grouped = df.groupby(agg_cols)[data_col].agg(agg_funcs)
    grouped.columns = [f"{data_col}_{f}" for f in agg_funcs]
    return grouped.reset_index()

